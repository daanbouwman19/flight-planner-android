package com.github.daanbouwman.flightplanner.aircraftart

import com.github.daanbouwman.flightplanner.model.AircraftSpec
import java.io.File

/**
 * Writes `AircraftShapes.kt`, the table `:core:aircraftart` compiles.
 *
 * Deterministic: the order is the manifest's, nothing in it depends on the
 * clock or the machine, and rebuilding from unchanged models produces no diff.
 */
object KotlinTable {

    /** ICAO designators that mean "none assigned" and must not pick an outline for anyone else. */
    private val NOT_A_TYPE = setOf("", "ZZZZ")

    const val LAST_RESORT = "generic_piston_single"

    fun write(file: File, sources: List<ShapeSource>, shapes: Map<String, CachedShape>, seed: List<AircraftSpec>) {
        val built = sources.filter { it.id in shapes }
        require(built.any { it.id == LAST_RESORT }) { "The last-resort outline [$LAST_RESORT] has not been built" }

        val shapeOfRow = HashMap<RowKey, String>()
        for (source in built) for (row in source.rows) shapeOfRow[row] = source.id

        val rows = seed.mapNotNull { spec ->
            shapeOfRow[RowKey(spec.manufacturer, spec.variant)]?.let { "${spec.manufacturer}|${spec.variant}" to it }
        }
        val icaoDefaults = LinkedHashMap<String, String>()
        for (spec in seed) {
            val code = spec.icaoCode.trim().uppercase()
            if (code in NOT_A_TYPE) continue
            val id = shapeOfRow[RowKey(spec.manufacturer, spec.variant)] ?: continue
            icaoDefaults.putIfAbsent(code, id)
        }
        val categories = LinkedHashMap<String, String>()
        for (source in built) for (category in source.fallbackFor) {
            val key = category.trim().lowercase()
            require(categories.put(key, source.id) == null) { "Category '$category' falls back to two outlines" }
        }

        val text = buildString {
            appendLine("// Generated by :tools:aircraftart from tools/aircraftart/data/shapes.ini. Do not edit.")
            appendLine("// Rebuild on a machine with the simulator installed:")
            appendLine("//     ./gradlew :tools:aircraftart:run --args=\"build\"")
            appendLine()
            appendLine("package com.github.daanbouwman.flightplanner.aircraftart")
            appendLine()
            appendLine("import com.github.daanbouwman.flightplanner.aircraftart.AircraftShape.Provenance")
            appendLine()
            appendLine("/** Every outline the app ships, and the tables [AircraftArt] resolves an airframe through. */")
            appendLine("internal object AircraftShapes {")
            appendLine()
            appendLine("    /** The outline for an airframe nothing else matches. */")
            appendLine("    const val LAST_RESORT = ${literal(LAST_RESORT)}")
            appendLine()
            appendLine("    val all: List<AircraftShape> = listOf(")
            for (source in built) {
                val shape = shapes.getValue(source.id)
                appendLine("        AircraftShape(")
                appendLine("            id = ${literal(source.id)},")
                appendLine("            label = ${literal(source.label)},")
                appendLine("            spanCm = ${shape.spanCm},")
                appendLine("            lengthCm = ${shape.lengthCm},")
                appendLine("            provenance = Provenance.${source.provenance.name},")
                appendLine("            pathData = ${literal(shape.path)},")
                appendLine("        ),")
            }
            appendLine("    )")
            appendLine()
            appendLine("    /** Seed rows, as `manufacturer|variant`, to the outline drawn for each. */")
            appendLine("    val rows: Map<String, String> = mapOf(")
            for ((key, id) in rows) appendLine("        ${literal(key)} to ${literal(id)},")
            appendLine("    )")
            appendLine()
            appendLine("    /** ICAO type designator to the outline of the first seed row that carries it. */")
            appendLine("    val icaoDefaults: Map<String, String> = mapOf(")
            for ((code, id) in icaoDefaults) appendLine("        ${literal(code)} to ${literal(id)},")
            appendLine("    )")
            appendLine()
            appendLine("    /** Lower-cased category to the generic outline that stands in for it. */")
            appendLine("    val categories: Map<String, String> = mapOf(")
            for ((category, id) in categories) appendLine("        ${literal(category)} to ${literal(id)},")
            appendLine("    )")
            appendLine("}")
        }
        file.parentFile.mkdirs()
        file.writeText(text)
    }

    private fun literal(value: String): String {
        val escaped = value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        return "\"$escaped\""
    }
}
